/// Built once: `keys` rebuilds the whole table on every read.
final Map<String, String> _englishKeys = AppTranslations().keys['en_US'] ?? const {};

/// The English wording for a key, for the Hindi and Bhojpuri screens that pair
/// both languages the way the party's printed material does. Returns null on
/// the English locale, where a second line would only repeat the first.
String? englishLabel(String key) {
  if ((Get.locale?.languageCode ?? 'en') == 'en') return null;
  final value = _englishKeys[key];
  if (value == null || value.isEmpty || value == key) return null;
  return value;
}
